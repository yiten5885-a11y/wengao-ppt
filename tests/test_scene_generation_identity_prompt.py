        self.assertEqual(captured["scene_request"]["identity_prompt"],
                         WAR_ROOM_SCENE["image_plan"]["positive_prompt"])
        self.assertIn("应急指挥室", captured["prompt"])
        self.assertNotIn("prompt_focus", captured["scene_request"])


class ModelTransportRetryTests(unittest.TestCase):
    """上游掐断连接不能算"这个场景不成立"。

    2026-10-26 job-83f27a9a9dc2：规划调用抛 RemoteDisconnected，旧实现直接判
    VISUAL.SCENE_PLAN_FAILED，整稿渲染失败——而它只是一次连接被断开。

    注入的假调用没有真实端点，健康门无从探测；重试节奏（10 秒 / 30 秒）在这里
    没有意义，压成 0 以免用例白等 40 秒。真实重试的节奏由
    tests/test_local_model_transport.py 覆盖。
    """

    def setUp(self):
        from unittest import mock
        from wengao_ppt import scene_model
        patcher = mock.patch.multiple(scene_model, _LOCAL_TRANSPORT_BACKOFF_S=(0.0, 0.0))
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_remote_disconnected_is_a_transport_failure(self):
        import http.client
        from wengao_ppt.scene_model import classify_external_model_failure

        classified = classify_external_model_failure(
            http.client.RemoteDisconnected("Remote end closed connection without response"))
        self.assertIsNotNone(classified)
        self.assertEqual(classified.code, "MODEL.TRANSPORT_ERROR")

    def test_transport_retry_recovers_within_the_budget(self):
        import http.client
        from wengao_ppt.scene_model import _call_json_payload_with_transport_retry

        calls = {"n": 0}

        def flaky_call(model, prompt):
            calls["n"] += 1
            if calls["n"] < 3:
                raise http.client.RemoteDisconnected("remote closed")
            return {"response": '{"scenes": [], "page_coverage": []}'}

        payload, meta, _raw = _call_json_payload_with_transport_retry(
            "m", "p", flaky_call, phase="规划", attempts=3)
        self.assertEqual(payload, {"scenes": [], "page_coverage": []})
        self.assertEqual(calls["n"], 3)

    def test_transport_retry_gives_up_after_the_budget(self):
        import http.client
        from wengao_ppt.scene_model import (
            SceneModelError, _call_json_payload_with_transport_retry)

        calls = {"n": 0}

        def dead_call(model, prompt):
            calls["n"] += 1
            raise http.client.RemoteDisconnected("remote closed")

        with self.assertRaises(SceneModelError) as ctx:
            _call_json_payload_with_transport_retry("m", "p", dead_call,
                                                    phase="规划", attempts=2)
        self.assertEqual(ctx.exception.code, "MODEL.TRANSPORT_ERROR")
        self.assertEqual(calls["n"], 2)



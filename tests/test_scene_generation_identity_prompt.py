def _noise_png(width: int = 800, height: int = 480, seed: int = 20261026) -> bytes:
    rng = random.Random(seed)
    image = Image.new("RGB", (width, height))
    image.putdata([(rng.randrange(256), rng.randrange(256), rng.randrange(256))
                   for _ in range(width * height)])
    out = io.BytesIO()
    image.save(out, format="PNG")
    return out.getvalue()


def _passing_review(scene, data) -> dict:
    """A review that confirms every role, bound to the exact generated bytes."""
    import hashlib
    return {"status": "PASSED", "reason_code": "NONE", "confidence": "high",
            "scene_match": True, "subject_visible": True, "action_visible": True,
            "setting_visible": True, "photographic": True,
            "image_sha256": hashlib.sha256(data).hexdigest()}


class _FakeCloudClient:
    """Stands in for the user-configured cloud image service."""

    captured: dict = {}


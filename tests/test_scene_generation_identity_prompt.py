        captured = self._generate(reviewer=_passing_review,
                                  review_focus_role="setting")
        self.assertEqual(captured["scene_request"]["prompt_focus"], "应急指挥室")
        self.assertIn("The scene clearly shows 应急指挥室", captured["prompt"])

